#!/usr/bin/env python3
"""Project the Copilot CLI's own JSON-RPC contract into an OpenAPI 3.1 document.

The GitHub Copilot CLI npm package (`@github/copilot`) ships the machine-readable
contract its SDKs are generated from:

    <cli-package>/schemas/api.schema.json            (JSON Schema draft 2019-09)
    <cli-package>/schemas/session-events.schema.json (JSON Schema draft 2019-09)

The Copilot Go SDK v1.0.11 is itself generated from the first of those ("Code
generated by scripts/codegen/go.ts; DO NOT EDIT. Source: api.schema.json", at the
top of its rpc/zrpc.go), so this projection reads the same upstream source the Go
SDK does instead of re-deriving the protocol from Go types.

Every JSON-RPC method becomes `POST /rpc/<rpcMethod>` carrying that method's
params schema and returning its result schema; every session event kind becomes a
component schema under the discriminated `SessionEvent` union.

Usage:
    python3 generate_sdk_openapi.py --schemas <dir> --out copilot-sdk.openapi.yaml
    python3 generate_sdk_openapi.py --schemas <dir> --out <file> --check
"""

from __future__ import annotations

import argparse
import copy
import difflib
import json
import pathlib
import sys

import yaml

GROUPS = {
    "server": "Process-wide methods the SDK client calls on the CLI server.",
    "session": "Per-session methods the SDK client calls on the CLI server.",
    "clientSession": "Reverse calls: the CLI server calls these on the SDK client, per session.",
    "clientGlobal": "Reverse calls: the CLI server calls these on the SDK client, process-wide.",
}

STRIP_KEYS = ("$schema", "$id", "definitions")

# Keywords a schema node may carry in OpenAPI 3.1 (which is JSON Schema 2020-12).
# The CLI schemas also carry their own annotations - `stability`, `internal`,
# `rpcMethod` and friends - which are legal JSON Schema annotations but illegal
# OpenAPI, so they are moved to `x-` extensions rather than dropped.
SCHEMA_KEYWORDS = frozenset(
    {
        "$ref", "$comment", "type", "title", "description", "default", "examples", "enum", "const",
        "format", "deprecated", "readOnly", "writeOnly", "properties", "patternProperties",
        "additionalProperties", "unevaluatedProperties", "propertyNames", "required",
        "minProperties", "maxProperties", "items", "prefixItems", "contains", "minContains",
        "maxContains", "minItems", "maxItems", "uniqueItems", "unevaluatedItems", "minimum",
        "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf", "minLength", "maxLength",
        "pattern", "allOf", "anyOf", "oneOf", "not", "if", "then", "else", "dependentSchemas",
        "dependentRequired", "discriminator", "externalDocs", "xml", "example",
    }
)

# Keywords whose value is a single nested schema, a list of schemas, or a map of
# schemas. Everything else at a schema node is a plain annotation value.
SUBSCHEMA_KEYS = ("items", "not", "if", "then", "else", "contains", "propertyNames",
                  "additionalProperties", "unevaluatedItems", "unevaluatedProperties")
SUBSCHEMA_LIST_KEYS = ("allOf", "anyOf", "oneOf", "prefixItems")
SUBSCHEMA_MAP_KEYS = ("properties", "patternProperties", "dependentSchemas")

# Renames forced by the two schemas disagreeing about a name, filled in by
# build(). A cross-file `session-events.schema.json#/definitions/X` pointer is
# always resolved through this table, whichever schema the pointer lives in.
EVENT_RENAME: dict[str, str] = {}


def normalize(node, rename):
    """Rewrite `#/definitions/X` pointers and move stray keywords to `x-`.

    `node` is always a schema node: recursion descends only through the keywords
    whose values are schemas, so a property literally named `stability` is left
    alone while a `stability` ANNOTATION on a schema becomes `x-stability`.
    """
    if not isinstance(node, dict):
        return node
    result = {}
    for key, value in node.items():
        if key in STRIP_KEYS:
            continue
        if key == "$ref" and isinstance(value, str):
            # Both a local `#/definitions/X` pointer and the api schema's
            # cross-file `session-events.schema.json#/definitions/X` pointer land
            # in the one merged component map.
            if "#/definitions/" in value:
                cross_file = value.startswith("session-events.schema.json")
                name = value.split("#/definitions/", 1)[1]
                table = EVENT_RENAME if cross_file else rename
                result[key] = "#/components/schemas/" + table.get(name, name)
                continue
        if key in SUBSCHEMA_KEYS:
            result[key] = normalize(value, rename) if isinstance(value, dict) else value
            continue
        if key in SUBSCHEMA_LIST_KEYS and isinstance(value, list):
            result[key] = [normalize(item, rename) for item in value]
            continue
        if key in SUBSCHEMA_MAP_KEYS and isinstance(value, dict):
            result[key] = {name: normalize(sub, rename) for name, sub in value.items()}
            continue
        if key in SCHEMA_KEYWORDS or key.startswith("x-"):
            result[key] = value
            continue
        result["x-" + key] = value
    return result


def rewrite_refs(node, rename):
    return normalize(node, rename)


def walk_methods(node, path):
    """Yield (name_path, method_object) for every rpcMethod under `node`."""
    for key, value in node.items():
        if not isinstance(value, dict):
            continue
        if "rpcMethod" in value:
            yield path + [key], value
        else:
            yield from walk_methods(value, path + [key])


def body_of(schema_node, rename):
    schema = rewrite_refs(schema_node, rename)
    description = schema.pop("description", None)
    body = {"content": {"application/json": {"schema": schema}}}
    if description:
        body["description"] = description
    return body


def event_type_const(schema):
    """The literal value of an event schema's `type` discriminator, if any."""
    type_property = (schema.get("properties") or {}).get("type") or {}
    value = type_property.get("const")
    return value if isinstance(value, str) else None


def build(api, events):
    api_definitions = api["definitions"]
    event_definitions = events["definitions"]

    # 48 names appear in both schemas. The byte-identical ones collapse; the few
    # that genuinely differ keep the api meaning under the plain name and the
    # event meaning under a suffixed one, so neither is lost.
    rename = {}
    for name, schema in event_definitions.items():
        if name in api_definitions and json.dumps(schema, sort_keys=True) != json.dumps(
            api_definitions[name], sort_keys=True
        ):
            rename[name] = name + "SessionEvent"
    EVENT_RENAME.clear()
    EVENT_RENAME.update(rename)

    schemas = {}
    for name, schema in api_definitions.items():
        schemas[name] = rewrite_refs(copy.deepcopy(schema), {})
    for name, schema in event_definitions.items():
        target = rename.get(name, name)
        if target in schemas and target == name:
            continue
        schemas[target] = rewrite_refs(copy.deepcopy(schema), rename)

    # SessionEvent is the union the SDK event tap delivers. Give it an explicit
    # discriminator so a consumer dispatches on `type` instead of trial-decoding.
    union = rewrite_refs(copy.deepcopy(event_definitions["SessionEvent"]), rename)
    mapping = {}
    for member in union.get("anyOf", []):
        ref = member.get("$ref", "")
        literal = event_type_const(event_definitions.get(ref.rsplit("/", 1)[-1], {}))
        if literal:
            mapping[literal] = ref
    if mapping:
        union["discriminator"] = {"propertyName": "type", "mapping": dict(sorted(mapping.items()))}
    union["x-provenance"] = "published"
    schemas["SessionEvent"] = union

    paths = {}
    method_count = 0
    for group in GROUPS:
        for name_path, method in walk_methods(api[group], []):
            method_count += 1
            rpc_method = method["rpcMethod"]
            operation = {
                "operationId": group + "." + ".".join(name_path),
                "summary": (method.get("description") or rpc_method).split("\n")[0][:250],
                "tags": [group + "." + name_path[0] if len(name_path) > 1 else group],
                "x-rpc-method": rpc_method,
                "x-rpc-group": group,
                "x-provenance": "published",
            }
            if method.get("description"):
                operation["description"] = method["description"]
            if method.get("stability"):
                operation["x-stability"] = method["stability"]
            if method.get("internal"):
                operation["x-internal"] = True
            if method.get("params"):
                request = body_of(copy.deepcopy(method["params"]), rename)
                request.setdefault("description", "JSON-RPC `params` member.")
                request["required"] = True
                operation["requestBody"] = request
            if method.get("result"):
                response = body_of(copy.deepcopy(method["result"]), rename)
                response.setdefault("description", "JSON-RPC `result` member.")
            else:
                response = {"description": "JSON-RPC `result` member (no payload)."}
            operation["responses"] = {
                "200": response,
                "default": {
                    "description": "JSON-RPC `error` member.",
                    "content": {
                        "application/json": {"schema": {"$ref": "#/components/schemas/JsonRpcError"}}
                    },
                },
            }
            paths["/rpc/" + rpc_method] = {"post": operation}

    schemas["JsonRpcError"] = {
        "type": "object",
        "title": "JsonRpcError",
        "description": "The JSON-RPC 2.0 error object, modeled here because the transport carries it "
        "outside the CLI's own schemas.",
        "properties": {
            "code": {"type": "integer", "description": "JSON-RPC error code."},
            "message": {"type": "string", "description": "Short error description."},
            "data": {"description": "Implementation-defined error payload."},
        },
        "required": ["code", "message"],
        "x-provenance": "modeled-from-go-sdk-v1.0.11",
    }

    document = {
        "openapi": "3.1.0",
        "info": {
            "title": "GitHub Copilot CLI SDK protocol",
            "version": "1.0.80+go-sdk-1.0.11",
            "summary": "Reference projection of the Copilot CLI JSON-RPC session protocol.",
            "description": (
                "Documentation-grade reference for the JSON-RPC protocol the Copilot Go SDK\n"
                "v1.0.11 speaks to a `copilot` CLI server over stdio. It is NOT an HTTP API:\n"
                "each `POST /rpc/<method>` path stands for one JSON-RPC method, its request body\n"
                "is that method's `params` member and its `200` body is the `result` member.\n"
                "Generated by `spec/generate_sdk_openapi.py` from the CLI's own\n"
                "`schemas/api.schema.json` and `schemas/session-events.schema.json`.\n"
                "See spec/README.md for provenance and coverage.\n"
            ),
            "x-provenance": "published",
            "x-source-schemas": [
                "@github/copilot/schemas/api.schema.json",
                "@github/copilot/schemas/session-events.schema.json",
            ],
        },
        "servers": [
            {
                "url": "stdio://copilot",
                "description": "Not a network endpoint. The transport is framed JSON-RPC 2.0 over "
                "the CLI subprocess stdin and stdout.",
            }
        ],
        # A stdio subprocess has no transport authentication: the caller already
        # owns the process. Declared explicitly so the empty set is a statement
        # rather than an omission.
        "security": [],
        "tags": [{"name": name, "description": text} for name, text in GROUPS.items()],
        "paths": dict(sorted(paths.items())),
        "components": {"schemas": dict(sorted(schemas.items()))},
    }
    return document, method_count, len(mapping)


def render(schema_dir):
    api = json.loads((schema_dir / "api.schema.json").read_text())
    events = json.loads((schema_dir / "session-events.schema.json").read_text())
    document, method_count, event_count = build(api, events)
    header = (
        "# Generated by spec/generate_sdk_openapi.py from the Copilot CLI JSON Schemas.\n"
        "# DO NOT EDIT BY HAND. See spec/README.md.\n"
    )
    text = header + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)
    return text, method_count, event_count, len(document["components"]["schemas"])


def main(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument("--schemas", required=True, help="directory holding the two CLI JSON Schemas")
    parser.add_argument("--out", required=True)
    parser.add_argument("--check", action="store_true", help="regenerate and diff instead of writing")
    args = parser.parse_args(argv)

    text, method_count, event_count, schema_count = render(pathlib.Path(args.schemas))
    out = pathlib.Path(args.out)
    if args.check:
        current = out.read_text() if out.exists() else ""
        if current != text:
            sys.stdout.writelines(
                difflib.unified_diff(
                    current.splitlines(True), text.splitlines(True), "committed", "regenerated"
                )
            )
            print("spec is stale: regenerate with generate_sdk_openapi.py", file=sys.stderr)
            return 1
        print("spec up to date: %d methods, %d event kinds" % (method_count, event_count))
        return 0
    out.write_text(text)
    print(
        "wrote %s: %d methods, %d event kinds, %d schemas"
        % (out, method_count, event_count, schema_count)
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

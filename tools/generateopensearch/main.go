// Command generateopensearch derives one consumer client from the upstream
// spec-generated SDK, then delegates its test double to MockGen.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const (
	sdkModule  = "github.com/opensearch-project/opensearch-go/v5"
	outputFile = "opensearch_client_cgen.go"
)

var operations = []struct{ file, receiver, method string }{
	{"index", "DocumentClient", "Doc.Index"},
	{"search", "Client", "Search"},
}

func main() {
	if err := generate(); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	if err := run("mod", "download", sdkModule); err != nil {
		return err
	}
	directory, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", sdkModule).Output()
	if err != nil {
		return fmt.Errorf("locate pinned OpenSearch SDK: %w", err)
	}
	var signatures, implementations []string
	imports := map[string]bool{}
	var importLines []string
	for _, operation := range operations {
		command := exec.Command("go", "run", "github.com/vburenin/ifacemaker@v1.4.0",
			"-f", filepath.Join(strings.TrimSpace(string(directory)), "opensearchapi", "clients_gen.go"),
			"-f", filepath.Join(strings.TrimSpace(string(directory)), "opensearchapi", operation.file+"_gen.go"),
			"-s", operation.receiver, "-i", "IOpenSearchClient", "-p", "csf", "-d=false")
		command.Stderr = os.Stderr
		source, err := command.Output()
		if err != nil {
			return err
		}
		set := token.NewFileSet()
		file, err := parser.ParseFile(set, "interface.go", source, 0)
		if err != nil {
			return err
		}
		for _, item := range file.Imports {
			var rendered bytes.Buffer
			if err := format.Node(&rendered, set, item); err != nil {
				return err
			}
			line := rendered.String()
			if !imports[line] {
				imports[line] = true
				importLines = append(importLines, line)
			}
		}
		for _, declaration := range file.Decls {
			group, ok := declaration.(*ast.GenDecl)
			if !ok || group.Tok != token.TYPE {
				continue
			}
			for _, spec := range group.Specs {
				typeSpec := spec.(*ast.TypeSpec)
				contract, ok := typeSpec.Type.(*ast.InterfaceType)
				if !ok {
					continue
				}
				for _, method := range contract.Methods.List {
					function := method.Type.(*ast.FuncType)
					var signature bytes.Buffer
					if err := format.Node(&signature, set, function); err != nil {
						return err
					}
					methodSignature := method.Names[0].Name + strings.TrimPrefix(signature.String(), "func")
					signatures = append(signatures, methodSignature)
					var arguments []string
					for _, field := range function.Params.List {
						for _, name := range field.Names {
							arguments = append(arguments, name.Name)
						}
					}
					implementations = append(implementations, "func (sdk openSearchSDKClient) "+methodSignature+" { return sdk.client."+operation.method+"("+strings.Join(arguments, ", ")+") }")
				}
			}
		}
	}
	content := "// Code generated by Candacegen from the pinned OpenSearch SDK using ifacemaker; DO NOT EDIT.\npackage csf\nimport (\n" + strings.Join(importLines, "\n") + ")\n\n// IOpenSearchClient is the shared generated Index/Search contract.\ntype IOpenSearchClient interface {\n" + strings.Join(signatures, "\n") + "\n}\n\ntype openSearchSDKClient struct { client *opensearchapi.Client }\n" + strings.Join(implementations, "\n")
	formatted, err := format.Source([]byte(content))
	if err != nil {
		return err
	}
	if err := os.WriteFile(outputFile, formatted, 0644); err != nil {
		return err
	}
	return run("run", "go.uber.org/mock/mockgen@v0.6.0", "-source="+outputFile,
		"-destination=internal/mocks/opensearch.gen.go", "-package=csfmocks")
}

func run(arguments ...string) error {
	command := exec.Command("go", arguments...)
	command.Stdout, command.Stderr = os.Stdout, os.Stderr
	return command.Run()
}

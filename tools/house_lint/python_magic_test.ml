let corpus_cases root =
  let ignored = ["test_fixture.py"; "fixture_test.py"; "tests/missing.py";
    "vendor/missing.py"; "pkg/vendor/missing.py"; "research/missing.py";
    "third_party/missing.py"; "fixture.ml"] in
  expect "ignored inputs were opened or empty Python corpus failed"
    (Python_magic.check root ignored = empty);
  expect "empty Python corpus failed" (Python_magic.check root [] = empty);
  write root "generated.py" "# Generated by a fixture. DO NOT EDIT!\r\nnot python syntax (\n";
  expect "generated file was parsed or counted" (Python_magic.check root ["generated.py"] = empty);
  write root "fixture.py" "def one():\n    return 'unique'\n";
  let scan = Python_magic.check root ["fixture.py"; "fixture.py"] in
  expect "duplicate inventory doubled findings" (count_of scan = 1 && lines (findings_of scan) = [2] && errors_of scan = []);
  let scan = Python_magic.check root ["missing.py"] in
  expect "unreadable source passed" (count_of scan = 1 && errors_of scan <> []);
  let scan = Python_magic.check root ["../outside.py"] in
  expect "inventory escaped checkout" (errors_of scan <> [])

let error_cases root =
  List.iter (fun source ->
    write root "broken.py" source;
    let scan = Python_magic.check root ["broken.py"] in
    expect "invalid Python syntax passed" (count_of scan = 1 && findings_of scan = [] && errors_of scan <> []))
    ["def broken(:\n    return 'pending'\n";
     "def broken():\n    return ('pending'\n";
     "def broken():\n    return '''unterminated\n"];
  List.iter (fun literal ->
    write root "broken.py" ("VALUE = " ^ literal ^ "\n");
    expect "invalid escape in exempt declaration passed" (errors_of (Python_magic.check root ["broken.py"]) <> []))
    [{|"\xGG"|}; {|"\u12"|}; {|"\U00110000"|}; {|b"\xGG"|}];
  expect "raw or byte Unicode escapes were rejected"
    (check_source root {|def escapes():
    raw = r"\xGG"
    binary = b"\u12"
    valid = "\u00e9"
|} = []);
  write root "broken.py" "def broken(:\n";
  write root "fixture.py" "def one():\n    return 'unique'\n";
  let scan = Python_magic.check root ["broken.py"; "fixture.py"] in
  expect "syntax error suppressed other file findings" (count_of scan = 2 && lines (findings_of scan) = [2] && errors_of scan <> []);
  write root "invalid_utf8.py" "# \255\n";
  expect "invalid UTF-8 passed" (errors_of (Python_magic.check root ["invalid_utf8.py"]) <> []);
  Unix.symlink "fixture.py" (Filename.concat root "link.py");
  expect "source symlink bypassed shared path boundary" (errors_of (Python_magic.check root ["link.py"]) <> [])

let () =
  let root = Filename.temp_file "house-lint-python-" "" in
  Sys.remove root;
  Unix.mkdir root 0o700;
  Fun.protect ~finally:(fun () ->
    Sys.readdir root |> Array.iter (fun name -> Sys.remove (Filename.concat root name)); Unix.rmdir root)
    (fun () -> semantic_cases root; exemptions root; corpus_cases root; error_cases root);
  print_endline "Python magic-string native tests passed"

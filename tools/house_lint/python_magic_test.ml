let expect message condition = if not condition then failwith message
let write root name source =
  Out_channel.with_open_text (Filename.concat root name) (fun channel -> output_string channel source)
let lines findings = List.map (fun (finding : Source.finding) -> finding.line) findings
let count_of scan = scan.Python_magic.count
let findings_of scan = scan.Python_magic.findings
let errors_of scan = scan.Python_magic.errors
let empty = { Python_magic.count = 0; Python_magic.findings = []; Python_magic.errors = [] }
let check_source root source =
  write root "fixture.py" source;
  let scan = Python_magic.check root ["fixture.py"] in
  expect "production source count changed" (count_of scan = 1);
  expect "valid Python fixture failed parsing" (errors_of scan = []);
  List.iter (fun (finding : Source.finding) ->
    expect "wrong rule or source path" (finding.rule = "PY-MAGIC-STRING" && finding.path = "fixture.py")) (findings_of scan);
  findings_of scan

let semantic_cases root =
  let findings = check_source root {|def select(record, state):
    phase = "queued"
    if state == "ready":
        return record["status"]
    emit("dispatch", format="compact")
    return {"kind": "completed"}
|} in
  expect "semantic contexts or exact lines missed" (lines findings = [2; 3; 4; 5; 5; 6; 6]);
  expect "diagnostic does not recommend an owned name"
    (List.for_all (fun (finding : Source.finding) ->
      Python_magic.contains finding.message "name a constant or generated enum") findings);
  let findings = check_source root {|async def modes():
    value = r"raw_mode"
    await emit('''triple_mode''')
    value = "\u0072eady"
    value = "\x72eady"
    value = "\162eady"
    return "part_" "two"
|} in
  expect "raw, triple, escaped or concatenated strings missed" (lines findings = [2; 3; 4; 5; 6; 7]);
  let findings = check_source root {|class Handler:
    kind = "declaration"
    def dispatch(self):
        return "method_result"
lookup = lambda record: record["lambda_key"]
|} in
  expect "methods or lambdas missed" (lines findings = [4; 5])


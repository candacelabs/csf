let expect message condition = if not condition then failwith message
let selected source = Source.selected (Source.parse "sample.go" source)
let source = "package fixture\ntype Reader interface { Read(string) error }\n"
let line_banner = Codegen_header.banner |> List.map (fun line -> "// " ^ line ^ "\n") |> String.concat ""
let block_banner = "/*\n" ^ String.concat "\n" Codegen_header.banner ^ "\n*/\n"

let () =
  List.iter (fun header ->
    expect "generated header entered handwritten corpus" (not (selected (header ^ source))))
    ["// Code generated by fixture. DO NOT EDIT.\n";
     "// Code generated by fixture. DO NOT EDIT.\r\n";
     line_banner; block_banner;
     "//go:build fixture\n\n" ^ block_banner];
  List.iter (fun marker ->
    let header = "// ===== " ^ marker ^ " =====\n// " ^ Codegen_header.disclaimer ^ "\n" in
    expect "configured owner marker was not recognized" (not (selected (header ^ source)));
    expect "partial owner name exempted handwritten code"
      (selected ("// " ^ marker ^ "Extra; " ^ Codegen_header.disclaimer ^ "\n" ^ source));
    expect "owner without disclaimer exempted handwritten code"
      (selected ("// " ^ marker ^ "\n" ^ source))
  ) Codegen_header.ownership_markers;
  expect "disclaimer alone exempted handwritten code"
    (selected ("// " ^ Codegen_header.disclaimer ^ "\n" ^ source));
  expect "generator name alone exempted handwritten code"
    (selected ("// " ^ Codegen_header.generator_name ^ "; " ^ Codegen_header.disclaimer ^ "\n" ^ source));
  expect "quoted banner exempted handwritten code"
    (selected ("package fixture\nconst example = `" ^ block_banner ^ "`\n"));
  expect "body comment banner exempted handwritten code"
    (selected ("package fixture\nfunc Example() {\n" ^ block_banner ^ "}\n"));
  print_endline "generated source selection: native regressions passed"

let external_suites () =
  let api = "pkg/widget/widget.go", "package widget\nfunc Render() string { return \"\" }\n" in
  count "exported API with no external package" "CS-18-EXTERNAL" 1 [api];
  count "exported API with only in-package tests" "CS-18-EXTERNAL" 1 [api;
    "pkg/widget/widget_internal_test.go", "package widget\nfunc TestRender(t *testing.T) {}\n"];
  count "an external package with a Test function" "CS-18-EXTERNAL" 0 [api;
    "pkg/widget/widget_test.go", "package widget_test\nfunc TestRender(t *testing.T) {}\n"];
  count "an external package with a Ginkgo spec" "CS-18-EXTERNAL" 0 [api;
    "pkg/widget/widget_suite_test.go", "package widget_test\nvar _ = Describe(\"widget\", func() {})\n"];
  count "no exported API, no requirement" "CS-18-EXTERNAL" 0 [
    "pkg/hidden/hidden.go", "package hidden\nfunc render() string { return \"\" }\n";
    "app/tool/main.go", "package main\nfunc Run() {}\n"];
  count "exported types, values and methods are API" "CS-18-EXTERNAL" 3 [
    "pkg/a/a.go", "package a\ntype Widget struct{}\n";
    "pkg/b/b.go", "package b\nconst (\n  hidden = 1\n  Limit = 2\n)\n";
    "pkg/c/c.go", "package c\ntype widget struct{}\nfunc (w widget) Render() {}\n"];
  (* Anti-gaming: an empty external package file, an external package in
     another directory, and a production file declaring `_test` do not count. *)
  count "an external package with no spec" "CS-18-EXTERNAL" 1 [api;
    "pkg/widget/widget_test.go", "package widget_test\nimport _ \"testing\"\n"];
  count "an external package elsewhere" "CS-18-EXTERNAL" 1 [api;
    "pkg/other/widget_test.go", "package widget_test\nfunc TestRender(t *testing.T) {}\n"];
  let found = findings "CS-18-EXTERNAL" [api; "pkg/widget/a.go", "package widget\n\n\nfunc helper() {}\n"] in
  expect "reported at the first file that exports API, on its package clause"
    (List.map (fun (finding : Source.finding) -> finding.path, finding.line) found = ["pkg/widget/widget.go", 1])


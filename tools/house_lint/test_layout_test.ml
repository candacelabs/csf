let expect message condition = if not condition then failwith message

let parse (path, source) =
  let file = Source.parse path source in
  if Source.Node.has_error file.root then failwith (path ^ ": invalid fixture syntax");
  file

let modules = ["other", "github.com/example/other"; ".", "github.com/example/public"]

let findings rule sources =
  Test_layout.collect ~modules (List.map parse sources)
  |> List.filter (fun (finding : Source.finding) -> finding.rule = rule)

let count label rule expected sources =
  let actual = findings rule sources in
  if List.length actual <> expected then begin
    List.iter (fun (finding : Source.finding) ->
      Printf.eprintf "%s:%d %s %s\n" finding.path finding.line finding.rule finding.message) actual;
    failwith (Printf.sprintf "%s: expected %d %s findings, got %d" label expected rule (List.length actual))
  end


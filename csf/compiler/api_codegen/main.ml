let read path =
  let channel = open_in_bin path in
  Fun.protect ~finally:(fun () -> close_in channel)
    (fun () -> really_input_string channel (in_channel_length channel))

let write path content =
  let channel = open_out_bin path in
  Fun.protect ~finally:(fun () -> close_out channel) (fun () -> output_string channel content)

let () =
  try
    if Array.length Sys.argv <> 4 then
      failwith "usage: generate <descriptor.json> <output-directory> <go-output>";
    let root = Sys.argv.(2) in
    let api_text = read (Filename.concat root "openapi/adapter.openapi.json") in
    let generated = Api_projection.generate (Yojson.Safe.from_file Sys.argv.(1)) (Yojson.Safe.from_string api_text) in
    write Sys.argv.(3) generated;
    let newline = if String.ends_with ~suffix:"\n" api_text then "" else "\n" in
    write (Filename.concat root "brainspine.openapi.yaml") ("# Generated by generate.sh; do not edit.\n" ^ api_text ^ newline)
  with
  | Failure message | Sys_error message | Yojson.Json_error message ->
      Printf.eprintf "CSF API generation: %s\n" message; exit 1
  | Yojson.Safe.Util.Type_error (message, _) ->
      Printf.eprintf "CSF API generation: malformed input: %s\n" message; exit 1

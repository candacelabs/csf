open Api_projection

let expect message condition = if not condition then failwith message
let rejects action = match action () with
  | _ -> failwith "expected generation rejection"
  | exception Failure _ -> ()

let method_ name input output = `Assoc ["name", `String name;
  "inputType", `String input; "outputType", `String output]

let file package path names = `Assoc [
  "name", `String (package ^ ".proto"); "package", `String package;
  "options", `Assoc ["goPackage", `String path];
  "messageType", `List (List.map (fun name -> `Assoc ["name", `String name]) names)]

let test_rpc_types () =
  validate_operation (method_ "Compile" ".x.CompileRequest" ".x.CompileResponse");
  rejects (fun () -> validate_operation (method_ "Compile" ".x.Controller" ".x.Program"));
  let files = [file "a.v1" "example.invalid/a;av1" ["SharedRequest"; "SharedResponse"];
    file "b.v1" "example.invalid/b;bv1" ["SharedRequest"; "SharedResponse"]] in
  let methods = [method_ "First" ".a.v1.SharedRequest" ".a.v1.SharedResponse";
    method_ "Second" ".b.v1.SharedRequest" ".b.v1.SharedResponse"] in
  let imports, types = go_types files methods in
  expect "package alias order" (imports = ["example.invalid/a", "contract0"; "example.invalid/b", "contract1"]);
  expect "owner collision" (List.assoc ".a.v1.SharedRequest" types = "contract0.SharedRequest");
  expect "owner collision" (List.assoc ".b.v1.SharedRequest" types = "contract1.SharedRequest");
  rejects (fun () -> go_types [file "a.v1" "" ["SharedRequest"; "SharedResponse"]] [List.hd methods]);
  rejects (fun () -> go_types [] methods)

let test_recursive_schemas () =
  let ref_ name = `Assoc ["$ref", `String ("#/components/schemas/" ^ name)] in
  let components = `Assoc [
    "Request", `Assoc ["properties", `Assoc ["node", ref_ "Node"]];
    "Node", `Assoc ["properties", `Assoc ["next", ref_ "Node"]];
    "Unrelated", `Assoc ["type", `String "string"]] in
  let schema = schema_for_mcp (ref_ "Request") components in
  expect "unreachable schema leaked" (field "$defs" schema |> sorted_fields |> List.map fst = ["Node"; "Request"]);
  expect "recursive ref unchanged" (field "$defs" schema |> field "Node" |> field "properties" |> field "next" |> string "$ref" = "#/$defs/Node");
  expect "input mutated" (field "Node" components |> field "properties" |> field "next" |> string "$ref" = "#/components/schemas/Node");
  expect "unnecessary definitions" (schema_for_mcp (`Assoc []) components = `Assoc []);
  rejects (fun () -> schema_for_mcp (ref_ "Missing") components)

let fixture request_fields =
  let descriptor = `Assoc ["file", `List [
    `Assoc ["name", `String "adapter.proto"; "service", `List [
      `Assoc ["name", `String "Research"; "method", `List [
        method_ "GetSnapshot" ".x.GetSnapshotRequest" ".x.GetSnapshotResponse"]]]];
    `Assoc ["name", `String "x.proto"; "package", `String "x";
      "options", `Assoc ["goPackage", `String "example.invalid/x;pb"];
      "messageType", `List [
        `Assoc ["name", `String "GetSnapshotRequest"; "field", `List request_fields];
        `Assoc ["name", `String "GetSnapshotResponse"]]]]] in
  let route = `Assoc ["operationId", `String "Research_GetSnapshot"; "summary", `String "Read \"state\" safely."] in
  let api verb route = `Assoc ["paths", `Assoc ["/api/snapshot", `Assoc [verb, route]];
    "components", `Assoc ["schemas", `Assoc []]] in
  descriptor, api, route

let test_generation () =
  let descriptor, api, route = fixture [] in
  let output = generate descriptor (api "get" route) in
  expect "deterministic projection" (output = generate descriptor (api "get" route));
  expect "generated marker missing" (String.starts_with ~prefix:"// Code generated by Candacegen (csf/compiler/api_codegen)." output);
  let imports, entries = operations descriptor (api "get" route) in
  expect "missing import" (imports = ["example.invalid/x", "contract0"]);
  let op = List.hd entries in
  expect "Go type not owned" (op.request = "contract0.GetSnapshotRequest");
  expect "nonempty GET schema" (json_string op.schema = "{\"additionalProperties\":false,\"properties\":{},\"type\":\"object\"}");
  rejects (fun () -> generate descriptor (api "patch" route));
  rejects (fun () -> generate descriptor (`Assoc ["paths", `Assoc []; "components", `Assoc ["schemas", `Assoc []]]));
  let nonempty, api, route = fixture [`Assoc ["name", `String "ignored"]] in
  rejects (fun () -> generate nonempty (api "get" route));
  rejects (fun () -> generate descriptor (api "get" (`Assoc ["operationId", `String "Research_Unknown"])));
  expect "canonical key sorting" (json_string (`Assoc ["z", `Int 1; "a", `Int 2]) = "{\"a\":2,\"z\":1}")

let () = test_rpc_types (); test_recursive_schemas (); test_generation ();
  print_endline "OCaml API projection regressions passed"

import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

import codegen


class CodegenTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)

    def add(self, name, content):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode() if isinstance(content, str) else content)
        return {"path": name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}

    def test_mixed_native_generated_headers(self):
        records = [
            self.add("src/hand.go", "package sample\n\nfunc Run() {}\n"),
            self.add("src/generated.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage sample\n"),
            self.add("src/generated.py", "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\nvalue = 1\n"),
            self.add("src/generated.rs", "// This file is @generated by prost-build.\npub struct Item;\n"),
            self.add("src/candace.py", "# Code generated by Candacegen from a schema. DO NOT EDIT.\nvalue = 2\n"),
        ]
        report = codegen.calculate(self.root, records)
        self.assertEqual(report["metric"], "codegen_percentage")
        self.assertEqual(report["generated_files"], 4)
        self.assertEqual(report["handwritten_files"], 1)
        self.assertEqual(report["generated_lines"], 9)
        self.assertEqual(report["handwritten_lines"], 3)
        self.assertEqual(report["generated_percent"], 75.0)
        self.assertEqual(set(report["by_language"]), {"Go", "Python", "Rust"})

    def test_native_candacegen_comment_forms_and_long_leading_region(self):
        records = [
            self.add("web/page.html", "<!-- Code generated by Candacegen. DO NOT EDIT. -->\n<div></div>\n"),
            self.add("src/style.css", "/* Code generated by Candacegen. DO NOT EDIT. */\nbody {}\n"),
            self.add("src/widget.c", "/* Code generated by Candacegen. DO NOT EDIT. */\nint value;\n"),
            self.add("src/module.ml", "(* Code generated by Candacegen. DO NOT EDIT. *)\nlet value = 1\n"),
            self.add("src/Module.lean", "/- Code generated by Candacegen. DO NOT EDIT. -/\ndef value := 1\n"),
            self.add("src/long.go", "".join(f"// source comment {number}\n" for number in range(25))
                 + "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage sample\n"),
        ]
        report = codegen.calculate(self.root, records)
        self.assertEqual(report["generated_files"], 5)
        self.assertEqual(report["generated_lines"], 35)
        self.assertEqual(report["excluded_files"], 1)

    def test_marker_like_strings_after_comment_region_are_handwritten(self):
        for source in (
            'message = "/* Code generated by Candacegen. DO NOT EDIT. */"\n',
            'const text = "<!-- Code generated by Candacegen. -->";\n',
            'let text = "(* Code generated by Candacegen. *)"\n',
            'def text := "/- Code generated by Candacegen. -/"\n',
        ):
            self.assertFalse(codegen.is_generated(source))

    def test_versioned_ocaml_header_is_recognized_but_file_is_excluded(self):
        source = "(* Code generated by CandaceCodegen v0.1.0-dev; _cgen suffix. DO NOT EDIT. *)\nlet value = 1\n"
        self.assertTrue(codegen.is_generated(source))
        report = codegen.calculate(self.root, [self.add("src/model_cgen.ml", source)])
        self.assertEqual(report["generated_files"], 0)
        self.assertEqual(report["total_lines"], 0)
        self.assertEqual(report["excluded_files"], 1)
        self.assertIsNone(report["generated_percent"])
        self.assertFalse(codegen.is_generated(source.replace("CandaceCodegen", "CandaceCodegenOther")))

    def add_ocaml_sources(self):
        records = []
        for extension in ("ml", "mli", "ML", "MLI"):
            records.append(self.add(f"generated.{extension}",
                "(* Code generated by CandaceCodegen. DO NOT EDIT. *)\nlet value = 1\n"))
            records.append(self.add(f"authored.{extension}", "let value = 1\n\n"))
        return records

    def test_ocaml_does_not_change_code_or_documentation_accounting(self):
        records = [self.add("main.go", "package main\n"), self.add("generated.py",
                   "# Code generated by CandaceCodegen. DO NOT EDIT.\nvalue = 1\n"),
                   self.add("README.md", "# Notes\n<!-- csf:diagram graph -->\n"
                            "generated\n<!-- /csf:diagram graph -->\n")]
        baseline = codegen.calculate(self.root, records)
        ocaml = self.add_ocaml_sources()
        report = codegen.calculate(self.root, records + ocaml)
        for field in baseline.keys() - {"excluded_files"}:
            with self.subTest(field=field):
                self.assertEqual(report[field], baseline[field])
        self.assertEqual(report["excluded_files"], baseline["excluded_files"] + len(ocaml))
        self.assertNotIn("OCaml", report["by_language"])

    def test_ocaml_only_corpus_has_null_percentages(self):
        records = self.add_ocaml_sources()
        report = codegen.calculate(self.root, records)
        self.assertEqual(report["files"], [])
        self.assertEqual(report["by_language"], {})
        self.assertEqual(report["excluded_files"], len(records))
        self.assertEqual(report["generated_files"], 0)
        self.assertEqual(report["handwritten_files"], 0)
        for corpus in (report, report["documentation"]):
            self.assertEqual(corpus["generated_lines"], 0)
            self.assertEqual(corpus["handwritten_lines"], 0)
            self.assertEqual(corpus["total_lines"], 0)
            self.assertIsNone(corpus["generated_percent"])

    def add_gotth_code(self):
        return [
            self.add("candace/pkg/gotth/render.go", "package gotth\n\n"),
            self.add("candace/pkg/gotth/internal/protocol/live.pb.go",
                     "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage protocol\n"),
            self.add("candace/pkg/gotth/live/clientjs/runtime.js", "const runtime = {};\n"),
        ]

    def test_gotth_code_is_excluded_but_adjacent_prefix_is_counted(self):
        records = [self.add("candace/pkg/gotth-extra/adapter.go", "package adapter\n"),
                   self.add("README.md", "# Notes\n")]
        baseline = codegen.calculate(self.root, records)
        self.assertEqual([item["path"] for item in baseline["files"]],
                         ["candace/pkg/gotth-extra/adapter.go"])
        excluded = self.add_gotth_code()
        report = codegen.calculate(self.root, records + excluded)
        for field in baseline.keys() - {"excluded_files"}:
            with self.subTest(field=field):
                self.assertEqual(report[field], baseline[field])
        self.assertEqual(report["excluded_files"], baseline["excluded_files"] + len(excluded))
        self.assertEqual(report["excluded_code_extensions"], [".ml", ".mli"])
        self.assertEqual(report["excluded_code_paths"], ["candace/pkg/gotth/"])

    def test_gotth_markdown_keeps_documentation_accounting(self):
        sources = {
            "generated.md": "<!-- Generated by a tool; do not edit. -->\n# Generated\n",
            "authored.MARKDOWN": "# Authored\n\n",
        }
        outside = [self.add("docs/" + name, source) for name, source in sources.items()]
        inside = [self.add("candace/pkg/gotth/docs/" + name, source)
                  for name, source in sources.items()]
        baseline = codegen.calculate(self.root, outside)
        report = codegen.calculate(self.root, self.add_gotth_code() + inside)
        for field in baseline["documentation"].keys() - {"files"}:
            with self.subTest(field=field):
                self.assertEqual(report["documentation"][field], baseline["documentation"][field])
        self.assertEqual([item["path"] for item in report["documentation"]["files"]],
                         [record["path"] for record in inside])
        self.assertEqual(report["files"], [])
        self.assertEqual(report["by_language"], {})
        self.assertEqual(report["total_lines"], 0)
        self.assertIsNone(report["generated_percent"])

    def test_leading_comment_may_precede_native_header(self):
        self.assertTrue(codegen.is_generated(
            "// source proto: brainspine.proto\n// retained compiler note\n"
            "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage sample\n"))

    def test_empty_code_corpus_has_null_percentage(self):
        record = self.add("README.md", "# Not source\n")
        report = codegen.calculate(self.root, [record])
        self.assertIsNone(report["generated_percent"])
        self.assertEqual(report["total_lines"], 0)
        self.assertEqual(report["excluded_files"], 1)

    def test_unselected_large_generated_file_does_not_enter_denominator(self):
        selected = self.add("src/main.go", "package main\n")
        self.add("generated/all.go", "// Code generated by a generator. DO NOT EDIT.\n" + "x\n" * 10000)
        report = codegen.calculate(self.root, [selected])
        self.assertEqual(report["total_lines"], 1)
        self.assertEqual(report["generated_lines"], 0)
        self.assertEqual([item["path"] for item in report["files"]], ["src/main.go"])

    def test_modified_selected_source_is_reported_and_counted(self):
        record = self.add("main.go", "package main\n")
        (self.root / "main.go").write_text("package changed\n\n", encoding="utf-8")
        report = codegen.calculate(self.root, [record])
        self.assertEqual(report["modified_files"], ["main.go"])
        self.assertEqual(report["total_lines"], 2)

    def test_missing_and_unsafe_paths_fail(self):
        digest = "0" * 64
        with self.assertRaisesRegex(ValueError, "missing or non-regular"):
            codegen.calculate(self.root, [{"path": "missing.py", "sha256": digest}])
        with self.assertRaisesRegex(ValueError, "unsafe archive path"):
            codegen.calculate(self.root, [{"path": "../escape.py", "sha256": digest}])

    def test_duplicate_paths_fail_even_for_excluded_files(self):
        record = self.add("README.md", "notes\n")
        with self.assertRaisesRegex(ValueError, "duplicate record path"):
            codegen.calculate(self.root, [record, record])

    def test_symlink_record_path_fails(self):
        self.add("real.py", "value = 1\n")
        (self.root / "alias.py").symlink_to(self.root / "real.py")
        record = {"path": "alias.py", "sha256": "0" * 64}
        with self.assertRaisesRegex(ValueError, "symlink record path"):
            codegen.calculate(self.root, [record])

    def test_header_detection_ignores_marker_like_string(self):
        self.assertFalse(codegen.is_generated(
            'message = "// Code generated by Candacegen. DO NOT EDIT."\n'))
        self.assertFalse(codegen.is_generated(
            'print("Generated by the protocol buffer compiler. DO NOT EDIT!")\n'))
        self.assertTrue(codegen.is_generated(
            "// Code generated by Candacegen. DO NOT EDIT.\npackage sample\n"))

    def test_cli_reads_default_receipt_without_git(self):
        record = self.add("main.py", "value = 1\n")
        document = self.add("README.md", "<!-- Generated by a tool; do not edit. -->\n# Generated\n")
        (self.root / "SOURCE_RECEIPT.json").write_text(
            json.dumps({"files": [record, document]}), encoding="utf-8")
        script = Path(codegen.__file__)
        result = subprocess.run(
            [sys.executable, str(script), "--root", str(self.root)],
            check=True, capture_output=True, text=True,
        )
        report = json.loads(result.stdout)
        self.assertEqual(report["total_lines"], 1)
        self.assertEqual(report["documentation"]["generated_lines"], 2)
        self.assertEqual(report["documentation"]["generated_percent"], 100.0)
        self.assertEqual(result.stderr, "")

    def test_full_generated_markdown_uses_header_and_counts_blank_lines(self):
        records = [
            self.add("ontology_cgen.md", "<!-- Generated by csf/compiler/language; do not edit. -->\n"
                     "# Vocabulary\n\nA term.\n"),
            self.add("archived_ontology.md", "<!-- Generated by tools/csf-language; do not edit. -->\n"
                     "# Archived vocabulary\n"),
            self.add("guide.MARKDOWN", "\n<!-- Code generated by a tool. DO NOT EDIT! -->\n\n"),
        ]
        report = codegen.calculate(self.root, records)
        docs = report["documentation"]
        self.assertEqual(docs["scope"], "selected_archive_markdown")
        self.assertEqual(docs["generated_lines"], 9)
        self.assertEqual(docs["handwritten_lines"], 0)
        self.assertEqual(docs["total_lines"], 9)
        self.assertEqual(docs["generated_percent"], 100.0)
        self.assertEqual(docs["files"][0], {
            "path": "ontology_cgen.md", "generated_lines": 4,
            "handwritten_lines": 0, "total_lines": 4, "generated_percent": 100.0,
        })
        self.assertEqual(docs["files"][1]["generated_lines"], 2)
        self.assertEqual(report["total_lines"], 0)
        self.assertEqual(report["excluded_files"], 3)

    def test_mixed_markdown_counts_only_generated_region_interiors(self):
        source = (
            "# Architecture\n\n<!-- csf:diagram architecture -->\n"
            "<!-- Generated by csf/compiler/language; do not edit. -->\n"
            "```mermaid\nflowchart LR\na --> b\n```\n\n"
            "<!-- /csf:diagram architecture -->\nAuthored explanation.\n"
            "<!-- csf:diagram simulation -->\n```mermaid\nx --> y\n```\n"
            "<!-- /csf:diagram simulation -->\n"
        )
        record = self.add("README.md", source)
        docs = codegen.calculate(self.root, [record])["documentation"]
        self.assertEqual(docs["generated_lines"], 9)
        self.assertEqual(docs["handwritten_lines"], 7)
        self.assertEqual(docs["total_lines"], 16)
        self.assertEqual(docs["generated_percent"], 56.25)

    def test_unmarked_names_manual_mermaid_and_nonleading_headers_stay_authored(self):
        for source in (
            "# Authored_cgen\n",
            "```mermaid\nflowchart LR\na --> b\n```\n",
            "# Authored\n<!-- Generated by csf/compiler/language; do not edit. -->\n",
            "```markdown\n<!-- Generated by csf/compiler/language; do not edit. -->\n```\n",
            "<!-- Generated by csf/compiler/language -->\nNo do-not-edit declaration.\n",
            "Generated by csf/compiler/language; do not edit.\n",
            "<!-- Generated by an example --> Authored <!-- do not edit. -->\n",
        ):
            with self.subTest(source=source):
                record = self.add("merely_cgen.md", source)
                docs = codegen.calculate(self.root, [record])["documentation"]
                self.assertEqual(docs["generated_lines"], 0)
                self.assertEqual(docs["handwritten_lines"], len(source.splitlines()))

    def test_fenced_marker_examples_are_authored(self):
        for opener, closer in (("```markdown", "```"), ("~~~~", "~~~~~"),
                               ("  ```", "  ````")):
            with self.subTest(opener=opener):
                source = (f"{opener}\n<!-- csf:diagram missing_end -->\n"
                          f"<!-- csf:diagram -->\n{closer}\n"
                          "<!-- csf:diagram real -->\ngenerated\n<!-- /csf:diagram real -->\n")
                docs = codegen.calculate(self.root, [self.add("README.md", source)])["documentation"]
                self.assertEqual(docs["generated_lines"], 1)
                self.assertEqual(docs["handwritten_lines"], 6)

    def test_fence_closing_requires_matching_character_and_length(self):
        source = ("````markdown\n```\n~~~\n<!-- csf:diagram unmatched -->\n````\n")
        docs = codegen.calculate(self.root, [self.add("README.md", source)])["documentation"]
        self.assertEqual(docs["generated_lines"], 0)
        self.assertEqual(docs["handwritten_lines"], 5)

    def test_malformed_diagram_regions_fail(self):
        cases = (
            ("<!-- csf:diagram -->\n", "malformed"),
            ("<!-- csf:diagram invalid-name -->\n", "malformed"),
            ("<!-- csf:diagram a\n", "malformed"),
            ("<!-- /csf:diagram a -->\n", "unmatched"),
            ("<!-- csf:diagram a -->\n<!-- /csf:diagram b -->\n", "unmatched"),
            ("<!-- csf:diagram a -->\n<!-- csf:diagram b -->\n", "nested"),
            ("<!-- csf:diagram a -->\nnever closed\n", "unclosed"),
            ("<!-- csf:diagram a --> trailing\n", "malformed"),
        )
        for source, message in cases:
            with self.subTest(source=source):
                record = self.add("README.md", source)
                with self.assertRaisesRegex(ValueError, message + ".*README.md"):
                    codegen.calculate(self.root, [record])

    def test_full_generated_header_does_not_bypass_region_validation(self):
        record = self.add("README.md", "<!-- Generated by csf/compiler/language; do not edit. -->\n"
                          "<!-- csf:diagram unclosed -->\n")
        with self.assertRaisesRegex(ValueError, "unclosed"):
            codegen.calculate(self.root, [record])

    def test_empty_regions_and_empty_documents_have_no_generated_lines(self):
        records = [self.add("empty.md", ""), self.add("README.md",
                   "<!-- csf:diagram empty -->\n<!-- /csf:diagram empty -->\n")]
        docs = codegen.calculate(self.root, records)["documentation"]
        self.assertEqual(docs["generated_lines"], 0)
        self.assertEqual(docs["handwritten_lines"], 2)
        self.assertEqual(docs["generated_percent"], 0.0)
        self.assertIsNone(docs["files"][0]["generated_percent"])

    def test_no_markdown_has_null_documentation_percentage(self):
        records = [self.add("main.py", "value = 1\n"),
                   self.add("release-review_cgen.html", "<h1>Receipt</h1>\n")]
        report = codegen.calculate(self.root, records)
        docs = report["documentation"]
        self.assertEqual(docs["generated_lines"], 0)
        self.assertEqual(docs["handwritten_lines"], 0)
        self.assertEqual(docs["total_lines"], 0)
        self.assertIsNone(docs["generated_percent"])
        self.assertEqual(docs["files"], [])
        self.assertEqual(report["total_lines"], 2)

    def test_documentation_respects_selected_archive_paths_and_duplicate_content(self):
        source = "<!-- csf:diagram a -->\none generated line\n<!-- /csf:diagram a -->\n"
        records = [self.add("README.md", source), self.add("packaging/brain-spine/README.md", source)]
        self.add("unselected.md", "<!-- Generated by a tool; do not edit. -->\n" + "x\n" * 10000)
        self.add("unselected-broken.md", "<!-- csf:diagram invalid -->\n")
        docs = codegen.calculate(self.root, records)["documentation"]
        self.assertEqual(docs["generated_lines"], 2)
        self.assertEqual(docs["total_lines"], 6)
        self.assertEqual([item["path"] for item in docs["files"]],
                         ["README.md", "packaging/brain-spine/README.md"])

    def test_markdown_does_not_change_existing_code_accounting(self):
        records = [self.add("main.go", "package main\n"), self.add("page.html", "<p>Page</p>\n"),
                   self.add("generated.go", "// Code generated by a tool. DO NOT EDIT.\npackage main\n")]
        baseline = codegen.calculate(self.root, records)
        self.assertEqual(baseline["generated_percent"], 50.0)
        records.extend([self.add("README.md", "# Authored\n"), self.add("guide.markdown",
                        "<!-- Generated by a tool; do not edit. -->\nGenerated\n")])
        report = codegen.calculate(self.root, records)
        for field in baseline.keys() - {"documentation", "excluded_files"}:
            with self.subTest(field=field):
                self.assertEqual(report[field], baseline[field])
        self.assertEqual(report["excluded_files"], baseline["excluded_files"] + 2)
        self.assertEqual(report["documentation"]["total_lines"], 3)

    def test_modified_selected_markdown_is_reported_without_writing(self):
        record = self.add("README.md", "# Original\n")
        changed = b"# Edited\r\n\r\nNo final newline"
        (self.root / "README.md").write_bytes(changed)
        report = codegen.calculate(self.root, [record])
        self.assertEqual(report["modified_files"], ["README.md"])
        self.assertEqual(report["documentation"]["total_lines"], 3)
        self.assertEqual((self.root / "README.md").read_bytes(), changed)

    def test_selected_markdown_must_be_utf8(self):
        record = self.add("README.md", b"\xff")
        with self.assertRaisesRegex(ValueError, "selected source is not UTF-8: README.md"):
            codegen.calculate(self.root, [record])


if __name__ == "__main__":
    unittest.main()

#!/usr/bin/env python3
"""Measure generated physical lines in selected CSF archive code and Markdown.

This reports a source archive composition metric, not a derivability score,
quality measure, or proof that generated code replaces hand maintenance.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

from archive import valid_path


# Keep the selected source corpus explicit. Locks, documentation, data,
# configuration and OCaml generator-language files are intentionally outside
# this metric's denominator, including generated OCaml files.
LANGUAGES = {
    "Go": {".go"},
    "Python": {".py", ".pyi"},
    "Rust": {".rs"},
    "C": {".c", ".h"},
    "C++": {".cc", ".cpp", ".cxx", ".hh", ".hpp", ".hxx"},
    "JavaScript": {".js", ".jsx", ".mjs", ".cjs"},
    "TypeScript": {".ts", ".tsx", ".mts", ".cts"},
    "Lean": {".lean"},
    "Shell": {".sh", ".bash"},
    "SQL": {".sql"},
    "Protocol Buffers": {".proto"},
    "HTML": {".html", ".htm", ".vue", ".svelte"},
    "CSS": {".css", ".scss", ".sass", ".less"},
}
EXTENSIONS = {extension: language for language, extensions in LANGUAGES.items()
              for extension in extensions}
EXCLUDED_CODE_EXTENSIONS = (".ml", ".mli")
EXCLUDED_CODE_PATHS = ("candace/pkg/gotth/",)

_GO_HEADER = re.compile(r"^//\s*Code generated .+ DO NOT EDIT\.?\s*$")
_PROTO_PYTHON_HEADER = re.compile(
    r"^#\s*Generated by the protocol buffer compiler\.\s+DO NOT EDIT!?\s*$")
_CANDACEGEN_MARKER = re.compile(r"^Code generated by Candace(?:Code)?gen\b", re.IGNORECASE)
_PROST_MARKER = re.compile(r"^This file is @generated by prost-build\.", re.IGNORECASE)
_MARKDOWN_EXTENSIONS = {".md", ".markdown"}
_MARKDOWN_HEADER = re.compile(
    r"<!--\s*(?:Code\s+)?Generated by [^<>]+\bdo not edit[.!]?\s*-->", re.IGNORECASE)
_DIAGRAM_MARKER = re.compile(r"<!--\s*(/?)csf:diagram ([a-z][a-z0-9_]*)\s*-->")
_DIAGRAM_MARKER_START = re.compile(r"^(?:<!--\s*)?/?csf:diagram\b")
_MARKDOWN_FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")


def _line_totals(generated: int, total: int) -> dict:
    return {
        "generated_lines": generated,
        "handwritten_lines": total - generated,
        "total_lines": total,
        "generated_percent": round(100 * generated / total, 2) if total else None,
    }


def _generated_diagram_lines(name: str, lines: list[str]) -> int:
    """Validate generated regions while leaving fenced examples authored."""
    opened = None
    fence = None
    generated = 0
    for number, line in enumerate(lines, 1):
        stripped = line.strip()
        if fence is not None:
            if re.fullmatch(r" {0,3}" + fence[0] + "{" + str(len(fence)) + r",}\s*", line):
                fence = None
            continue
        if opened is None:
            match = _MARKDOWN_FENCE.fullmatch(line)
            if match is not None:
                delimiter, info = match.groups()
                if delimiter[0] != "`" or "`" not in info:
                    fence = delimiter
                    continue
        marker = _DIAGRAM_MARKER.fullmatch(stripped)
        if marker is None:
            if _DIAGRAM_MARKER_START.match(stripped):
                raise ValueError(f"malformed diagram marker: {name}:{number}")
            if opened is not None:
                generated += 1
            continue
        closing, diagram = marker.groups()
        if closing:
            if opened != diagram:
                raise ValueError(f"unmatched diagram end marker: {name}:{number}")
            opened = None
        else:
            if opened is not None:
                raise ValueError(f"nested diagram marker: {name}:{number}")
            opened = diagram
    if opened is not None:
        raise ValueError(f"unclosed diagram marker {opened}: {name}")
    return generated


def _documentation_file(name: str, source: str) -> dict:
    """Count whole generated documents or validated diagram interiors."""
    lines = source.splitlines()
    header = next((line.strip() for line in lines if line.strip()), "")
    full_generated = _MARKDOWN_HEADER.fullmatch(header) is not None
    generated = _generated_diagram_lines(name, lines)
    return {"path": name, **_line_totals(len(lines) if full_generated else generated,
                                        len(lines))}


def language_for(path: str) -> str | None:
    """Return the source language for a declared path, when selected."""
    extension = Path(path).suffix.lower()
    if extension in EXCLUDED_CODE_EXTENSIONS or path.startswith(EXCLUDED_CODE_PATHS):
        return None
    return EXTENSIONS.get(extension)


def is_generated(source: str) -> bool:
    """Recognize generator markers in leading comments, never executable text.

    Only the leading comment region is examined. This includes the Go
    generated-code disclaimer, protobuf's Python disclaimer, prost's Rust
    marker, and CandaceCodegen (or legacy Candacegen) headers using each
    language's comment form.
    """
    block_end = None
    for index, line in enumerate(source.splitlines()):
        stripped = line.strip()
        if not stripped:
            continue
        if index == 0 and stripped.startswith("#!"):
            continue
        content = None
        trailing = ""
        if block_end is not None:
            closed = block_end in stripped
            if closed:
                before, after = stripped.split(block_end, 1)
                content = before.strip()
                trailing = after.strip()
                block_end = None
            else:
                content = stripped
            if content.startswith("*"):
                content = content[1:].lstrip()
        else:
            for prefix in ("///", "//!", "//", "#", "--"):
                if stripped.startswith(prefix):
                    content = stripped[len(prefix):].lstrip()
                    break
            if content is None:
                for opener, closer in (("/*", "*/"), ("<!--", "-->"),
                                       ("(*", "*)"), ("/-", "-/")):
                    if stripped.startswith(opener):
                        content = stripped[len(opener):].lstrip()
                        if closer in content:
                            content, trailing = content.split(closer, 1)
                            content = content.rstrip()
                            trailing = trailing.strip()
                        else:
                            block_end = closer
                        break
        if content is None:
            return False

        if (_GO_HEADER.fullmatch(stripped) or
                _PROTO_PYTHON_HEADER.fullmatch(stripped) or
                _CANDACEGEN_MARKER.match(content) or _PROST_MARKER.match(content)):
            return True
        # Code after a closing block comment ends the leading comment region.
        if block_end is None and trailing:
            return False
    return False


def _checked_source(root: Path, record: dict, seen: set[str]) -> tuple[Path, bytes]:
    name = record.get("path")
    if not isinstance(name, str):
        raise ValueError(f"record path must be a string: {name!r}")
    valid_path(name)
    if name in seen:
        raise ValueError(f"duplicate record path: {name}")
    seen.add(name)
    path = root.joinpath(*valid_path(name).parts)
    for parent in (path, *path.parents):
        if parent.is_symlink():
            raise ValueError(f"symlink record path: {name}")
    if not path.is_file():
        raise ValueError(f"missing or non-regular record path: {name}")
    try:
        content = path.read_bytes()
    except OSError as error:
        raise ValueError(f"cannot read record path {name}: {error}") from error
    expected = record.get("sha256")
    if not isinstance(expected, str) or not re.fullmatch(r"[0-9a-fA-F]{64}", expected):
        raise ValueError(f"invalid manifest SHA-256 for {name}")
    return path, content


def calculate(root: Path, records: list[dict]) -> dict:
    """Count code and Markdown separately from selected archive records."""
    root = Path(root)
    generated_lines = handwritten_lines = 0
    generated_files = handwritten_files = excluded_files = 0
    modified_files = []
    files = []
    documentation_files = []
    by_language = {}
    seen = set()

    for record in records:
        if not isinstance(record, dict):
            raise ValueError("manifest file record must be an object")
        name = record.get("path")
        _, content = _checked_source(root, record, seen)
        language = language_for(name) if isinstance(name, str) else None
        markdown = Path(name).suffix.lower() in _MARKDOWN_EXTENSIONS
        if language is None:
            excluded_files += 1
            if not markdown:
                continue
        try:
            source = content.decode("utf-8")
        except UnicodeDecodeError as error:
            raise ValueError(f"selected source is not UTF-8: {name}") from error
        if hashlib.sha256(content).hexdigest() != record["sha256"].lower():
            modified_files.append(name)
        if markdown:
            documentation_files.append(_documentation_file(name, source))
            continue
        lines = len(source.splitlines())
        generated = is_generated(source)
        if language not in by_language:
            by_language[language] = {
                "generated_lines": 0,
                "handwritten_lines": 0,
                "total_lines": 0,
                "generated_percent": None,
            }
        bucket = "generated_lines" if generated else "handwritten_lines"
        by_language[language][bucket] += lines
        by_language[language]["total_lines"] += lines
        if generated:
            generated_files += 1
            generated_lines += lines
        else:
            handwritten_files += 1
            handwritten_lines += lines
        files.append({"path": name, "language": language,
                      "generated": generated, "lines": lines})

    total_lines = generated_lines + handwritten_lines
    generated_percent = round(100 * generated_lines / total_lines, 2) if total_lines else None
    for totals in by_language.values():
        if totals["total_lines"]:
            totals["generated_percent"] = round(
                100 * totals["generated_lines"] / totals["total_lines"], 2)

    return {
        "metric": "codegen_percentage",
        "scope": "selected_archive_code",
        "excluded_code_extensions": list(EXCLUDED_CODE_EXTENSIONS),
        "excluded_code_paths": list(EXCLUDED_CODE_PATHS),
        "generated_lines": generated_lines,
        "handwritten_lines": handwritten_lines,
        "total_lines": total_lines,
        "generated_percent": generated_percent,
        "generated_files": generated_files,
        "handwritten_files": handwritten_files,
        "excluded_files": excluded_files,
        "modified_files": modified_files,
        "by_language": by_language,
        "files": files,
        "documentation": {
            "scope": "selected_archive_markdown",
            **_line_totals(sum(item["generated_lines"] for item in documentation_files),
                           sum(item["total_lines"] for item in documentation_files)),
            "files": documentation_files,
            "definition": (
                "physical Markdown lines including comments and blank lines; selected "
                "archive files only; explicit generated headers mark whole documents, "
                "otherwise only csf:diagram interiors are generated and marker lines "
                "are handwritten; not a proof or derivability score"
            ),
        },
        "definition": (
            "physical lines including comments and blank lines; selected archive code "
            "after declared extension and path exclusions; not all shipped code, "
            "a proof or derivability score"
        ),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True,
                        help="extracted archive or prepared workspace root")
    parser.add_argument("--manifest", type=Path,
                        help="manifest path (default: ROOT/SOURCE_RECEIPT.json)")
    arguments = parser.parse_args(argv)
    manifest = arguments.manifest or arguments.root / "SOURCE_RECEIPT.json"
    try:
        receipt = json.loads(manifest.read_text(encoding="utf-8"))
        records = receipt["files"]
        if not isinstance(records, list):
            raise ValueError("manifest files must be an array")
        report = calculate(arguments.root, records)
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as error:
        print(f"codegen: {error}", file=sys.stderr)
        return 2
    print(json.dumps(report, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

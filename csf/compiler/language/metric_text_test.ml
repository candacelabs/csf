let expect message condition = if not condition then failwith message

let rejects expected source =
  match Metric_text.documentation_generated_lines ~name:"README.md" source with
  | _ -> failwith ("expected rejection: " ^ expected)
  | exception Metric_text.Error actual -> expect ("wrong diagnostic: " ^ actual) (actual = expected)

let test_physical_lines () =
  List.iter (fun (source, expected) ->
    expect ("incorrect splitlines: " ^ String.escaped source) (Metric_text.physical_lines source = expected)) [
    "", []; "a", ["a"]; "\n", [""]; "a\n", ["a"]; "\n\n", [""; ""];
    "a\r\nb\rc\nd", ["a"; "b"; "c"; "d"];
    "a\r\n\r\n", ["a"; ""];
    "a\011b\012c\028d\029e\030f\194\133g\226\128\168h\226\128\169i", ["a"; "b"; "c"; "d"; "e"; "f"; "g"; "h"; "i"];
    "a\031b", ["a\031b"];
    "é\r\n界\226\128\169", ["é"; "界"];
  ];
  List.iter (fun separator ->
    expect "terminal break adds no line" (Metric_text.physical_lines ("a" ^ separator) = ["a"]))
    ["\n"; "\r"; "\r\n"; "\011"; "\012"; "\028"; "\029"; "\030"; "\194\133"; "\226\128\168"; "\226\128\169"]


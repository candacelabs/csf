let test_unicode_word_ranges () =
  let ranges = Metric_unicode_cgen.word_ranges in
  expect "Unicode compatibility table is non-empty" (Array.length ranges > 0);
  Array.iteri (fun index (lower, upper) ->
    expect "Unicode word range is a valid scalar interval"
      (lower >= 0 && lower <= upper && upper <= 0x10ffff &&
       (upper < 0xd800 || lower > 0xdfff));
    if index > 0 then begin
      let _, previous_upper = ranges.(index - 1) in
      expect "Unicode word ranges are sorted, disjoint, and coalesced"
        (previous_upper + 1 < lower)
    end;
    expect "Unicode word range lower endpoint is recognized" (Metric_unicode_cgen.is_word lower);
    expect "Unicode word range upper endpoint is recognized" (Metric_unicode_cgen.is_word upper);
    if lower > 0 then
      expect "Unicode word range lower neighbor is excluded" (not (Metric_unicode_cgen.is_word (lower - 1)));
    if upper < 0x10ffff then
      expect "Unicode word range upper neighbor is excluded" (not (Metric_unicode_cgen.is_word (upper + 1))))
    ranges;
  List.iter (fun (point, expected) ->
    expect (Printf.sprintf "wrong Unicode word classification for U+%04X" point)
      (Metric_unicode_cgen.is_word point = expected)) [
    0x30, true; 0x5f, true; 0xe9, true; 0x301, false; 0x665, true;
    0x1f600, false; 0x20000, true; 0xd800, false; 0x110000, false;
  ]


let expect message condition = if not condition then failwith message
let write path content = Out_channel.with_open_bin path (fun channel -> output_string channel content)
let contains source needle =
  let rec search index = index + String.length needle <= String.length source &&
    (String.sub source index (String.length needle) = needle || search (index + 1)) in
  search 0

let rejects fragment action =
  try action (); failwith ("expected rejection: " ^ fragment)
  with Generation_metrics.Error message ->
    expect ("unexpected diagnostic: " ^ message) (contains message fragment)

let rec remove path =
  if (Unix.lstat path).Unix.st_kind = Unix.S_DIR then begin
    Sys.readdir path |> Array.iter (fun name -> remove (Filename.concat path name));
    Unix.rmdir path
  end else Unix.unlink path

let with_root action =
  let root = Filename.temp_file "generation-metrics-" "" in
  Unix.unlink root; Unix.mkdir root 0o700;
  Fun.protect ~finally:(fun () -> remove root) (fun () -> action root)

let record root name content =
  write (Filename.concat root name) content;
  `Assoc ["path", `String name; "sha256", `String (Sha256.to_hex (Sha256.string content))]

let test_composition () = with_root (fun root ->
  let records = [
    record root "manual.go" "package demo\n\nfunc Run() {}\n";
    record root "generated.go" "// Code generated by a tool. DO NOT EDIT.\npackage demo\n";
    record root "README.md" "# Intro\n<!-- csf:diagram a -->\ngenerated\n<!-- /csf:diagram a -->\n";
    record root "config.json" "{}\n";
  ] in
  ignore (record root "omitted.go" ("// Code generated by a tool. DO NOT EDIT.\n" ^ String.make 5000 '\n'));
  let report = Generation_metrics.calculate ~root records in
  expect "code total" (report.code.total_lines = 5);
  expect "code classifications" (report.code.generated_lines = 2 && report.code.non_generated_lines = 3);
  expect "both code percentages" (report.code.generated_percent = Some 40. && report.code.non_generated_percent = Some 60.);
  expect "file classifications" (report.generated_files = 1 && report.non_generated_files = 1 && report.excluded_files = 2);
  expect "separate Markdown total" (report.documentation.total_lines = 4 && report.documentation.generated_lines = 1);
  expect "separate Markdown percentages" (report.documentation.generated_percent = Some 25. && report.documentation.non_generated_percent = Some 75.);
  expect "selected corpus" (List.length report.files = 2 && List.length report.documentation_files = 1);
  expect "unchanged provenance" (report.modified_files = []);
  expect "language totals" (List.assoc "Go" report.by_language = report.code);
  write (Filename.concat root "manual.go") "package edited\n";
  let changed = Generation_metrics.calculate ~root records in
  expect "modified bytes counted and identified" (changed.modified_files = ["manual.go"] && changed.code.total_lines = 3))

let test_empty () = with_root (fun root ->
  let empty = Generation_metrics.calculate ~root [] in
  expect "empty code percentages null" (empty.code.generated_percent = None && empty.code.non_generated_percent = None);
  expect "empty Markdown percentages null" (empty.documentation.generated_percent = None && empty.documentation.non_generated_percent = None);
  let empty_file = Generation_metrics.calculate ~root [record root "empty.go" ""] in
  expect "zero-line file counted without fabricated percentage" (empty_file.non_generated_files = 1 && empty_file.code.non_generated_percent = None))

let test_ocaml_exclusion () = with_root (fun root ->
  let selected = [record root "main.go" "package demo\n";
    record root "generated.go" "// Code generated by a tool. DO NOT EDIT.\npackage demo\n";
    record root "README.md" "<!-- Generated by a tool; do not edit. -->\n# Docs\n"] in
  let baseline = Generation_metrics.calculate ~root selected in
  let generated = "(* Code generated by CandaceCodegen. DO NOT EDIT. *)\n" in
  let excluded = [record root "generated.ml" (generated ^ "let value = 1\n");
    record root "generated.mli" (generated ^ "val value : int\n");
    record root "manual.ML" "let value = 1\n";
    record root "manual.MLI" "val value : int\n"] in
  let report = Generation_metrics.calculate ~root (selected @ excluded) in
  expect "OCaml files only increment excluded count"
    ({ report with excluded_files = baseline.excluded_files } = baseline &&
     report.excluded_files = baseline.excluded_files + List.length excluded);
  let only = Generation_metrics.calculate ~root excluded in
  expect "OCaml-only corpus has no code or document denominator"
    (only.code.total_lines = 0 && only.code.generated_percent = None &&
     only.code.non_generated_percent = None && only.documentation.total_lines = 0 &&
     only.generated_files = 0 && only.non_generated_files = 0 && only.excluded_files = 4))

let test_gotth_exclusion () = with_root (fun root ->
  List.iter (fun path -> Unix.mkdir (Filename.concat root path) 0o700)
    ["candace"; "candace/pkg"; "candace/pkg/gotth"; "candace/pkg/gotth/live";
     "candace/pkg/gotth/gen"; "candace/pkg/gotth-extra"];
  let selected = [record root "candace/pkg/gotth-extra/manual.go" "package adjacent\n";
    record root "generated.go" "// Code generated by a tool. DO NOT EDIT.\npackage demo\n";
    record root "candace/pkg/gotth/README.md" "<!-- Generated by a tool; do not edit. -->\n# Docs\n"] in
  let baseline = Generation_metrics.calculate ~root selected in
  let excluded = [record root "candace/pkg/gotth/live/app.go" "package live\n";
    record root "candace/pkg/gotth/gen/wire.pb.go" "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage wire\n"] in
  let report = Generation_metrics.calculate ~root (selected @ excluded) in
  expect "gotth code excluded while adjacent code and gotth Markdown stay selected"
    ({ report with excluded_files = baseline.excluded_files } = baseline &&
     report.excluded_files = baseline.excluded_files + 2 &&
     report.code.total_lines = 3 && report.documentation.generated_lines = 2);
  match Generation_metrics.to_json report with
  | `Assoc fields ->
      expect "report declares excluded extensions"
        (List.assoc "excluded_code_extensions" fields = `List [`String ".ml"; `String ".mli"]);
      expect "report declares exact excluded path prefix"
        (List.assoc "excluded_code_paths" fields = `List [`String "candace/pkg/gotth/"])
  | _ -> failwith "report must be an object")

let test_validation () = with_root (fun root ->
  let good = record root "main.go" "package demo\n" in
  let bad name = `Assoc ["path", `String name; "sha256", `String (String.make 64 '0')] in
  List.iter (fun name -> rejects "unsafe archive path" (fun () ->
    ignore (Generation_metrics.calculate ~root [bad name]))) [""; "/absolute.go"; "../escape.go"; "./main.go"; "a//b.go"; "a/../b.go"; "a\\b.go"];
  rejects "duplicate record" (fun () -> ignore (Generation_metrics.calculate ~root [good; good]));
  rejects "missing or non-regular" (fun () -> ignore (Generation_metrics.calculate ~root [bad "missing.go"]));
  Unix.symlink "main.go" (Filename.concat root "alias.go");
  rejects "symlink record" (fun () -> ignore (Generation_metrics.calculate ~root [bad "alias.go"]));
  rejects "SHA-256" (fun () -> ignore (Generation_metrics.calculate ~root [`Assoc ["path", `String "main.go"; "sha256", `String "invalid"]]));
  rejects "UTF-8" (fun () -> ignore (Generation_metrics.calculate ~root [record root "invalid.go" "\255"]));
  let excluded = Generation_metrics.calculate ~root [record root "image.png" "\255"] in
  expect "excluded binary remains outside denominator" (excluded.excluded_files = 1 && excluded.code.total_lines = 0))

let test_manifest () = with_root (fun root ->
  let manifest = Filename.concat root "SOURCE_RECEIPT.json" in
  let records = [record root "main.py" "value = 1\n"] in
  write manifest (Yojson.Safe.to_string (`Assoc ["files", `List records]));
  expect "manifest selection" (Generation_metrics.read_manifest manifest = records);
  List.iter (fun document -> write manifest document;
    rejects "manifest" (fun () -> ignore (Generation_metrics.read_manifest manifest))) ["null"; "{}"; "{\"files\":null}"; "{\"files\":{}}"])

let test_duplicate_members () = with_root (fun root ->
  let manifest = Filename.concat root "SOURCE_RECEIPT.json" in
  let records = [record root "main.py" "value = 1\n"] in
  let selected = Yojson.Safe.to_string (`List records) in
  write manifest ("{\"files\":[],\"files\":" ^ selected ^ "}");
  expect "last files member selects records" (Generation_metrics.read_manifest manifest = records);
  write manifest ("{\"files\":" ^ selected ^ ",\"files\":[]}");
  expect "last files member can select empty corpus" (Generation_metrics.read_manifest manifest = []);
  let hash = Sha256.to_hex (Sha256.string "value = 1\n") in
  let report = Generation_metrics.calculate ~root [`Assoc [
    "path", `String "missing.py"; "path", `String "main.py";
    "sha256", `String "invalid"; "sha256", `String hash]] in
  expect "last record members are authoritative" (report.code.total_lines = 1 && report.modified_files = []);
  rejects "missing or non-regular" (fun () -> ignore (Generation_metrics.calculate ~root [`Assoc [
    "path", `String "main.py"; "path", `String "missing.py"; "sha256", `String hash]])))

let test_manifest_lexical_extensions () = with_root (fun root ->
  let manifest = Filename.concat root "SOURCE_RECEIPT.json" in
  List.iter (fun (fragment, document) -> write manifest document;
    rejects fragment (fun () -> ignore (Generation_metrics.read_manifest manifest))) [
    "comments", "/* note */ {\"files\":[]}";
    "comments", "{\"files\":[]}// note";
    "keys must be quoted", "{files:[]}";
    "raw control", "{\"files\":[],\"note\":\"line\nline\"}";
  ];
  write manifest "{\"files\":[],\"note\":\"// /* \\\" / \\\\ \\n\",\"extra\":NaN}";
  expect "quoted comment syntax and escaped controls remain JSON strings"
    (Generation_metrics.read_manifest manifest = []))

let () =
  List.iter (fun test -> test ()) [test_composition; test_empty; test_ocaml_exclusion; test_gotth_exclusion; test_validation;
    test_manifest; test_duplicate_members; test_manifest_lexical_extensions];
  print_endline "native generation metrics tests passed"

exception Error of string

let scalar source offset =
  let decoded = String.get_utf_8_uchar source offset in
  Uchar.to_int (Uchar.utf_decode_uchar decoded), Uchar.utf_decode_length decoded

let line_break = function
  | 0x0a | 0x0b | 0x0c | 0x0d | 0x1c | 0x1d | 0x1e | 0x85 | 0x2028 | 0x2029 -> true
  | _ -> false

let physical_lines source =
  let length = String.length source in
  let rec scan start offset lines =
    if offset = length then
      List.rev (if start = length then lines else String.sub source start (length - start) :: lines)
    else
      let point, width = scalar source offset in
      if not (line_break point) then scan start (offset + width) lines
      else
        let next = offset + width in
        let next = if point = 0x0d && next < length && source.[next] = '\n' then next + 1 else next in
        scan next next (String.sub source start (offset - start) :: lines)
  in
  scan 0 0 []

(* Python's Unicode whitespace includes the ASCII information separators,
   unlike the Unicode White_Space property alone. *)
let whitespace point =
  (point >= 0x09 && point <= 0x0d) || (point >= 0x1c && point <= 0x20) ||
  point = 0x85 || point = 0xa0 || point = 0x1680 ||
  (point >= 0x2000 && point <= 0x200a) || point = 0x2028 || point = 0x2029 ||
  point = 0x202f || point = 0x205f || point = 0x3000

(* The patterns have ASCII literals but Unicode whitespace and word classes.
   Preserve literal spaces, and encode the Unicode classes as single bytes.
   Four non-ASCII letters also match ASCII literals under Python IGNORECASE. *)
let normalized source =
  let result = Buffer.create (String.length source) in
  let rec scan offset =
    if offset < String.length source then begin
      let point, width = scalar source offset in
      let character = match point with
        | 0x20 -> ' '
        | point when whitespace point -> '\t'
        | point when point < 0x80 -> Char.chr point
        | 0x130 -> '\130' | 0x131 -> '\131' | 0x17f -> '\132' | 0x212a -> '\133'
        | point when Metric_unicode_cgen.is_word point -> '\128'
        | _ -> '\129' in
      Buffer.add_char result character;
      scan (offset + width)
    end in
  scan 0;
  Buffer.contents result

let folded source = String.map (function
  | '\130' | '\131' -> 'i' | '\132' -> 's' | '\133' -> 'k'
  | character -> Char.lowercase_ascii character) source

let word_character = function
  | 'a' .. 'z' | 'A' .. 'Z' | '0' .. '9' | '_' | '\128' | '\130' .. '\133' -> true
  | _ -> false

let space = function ' ' | '\t' -> true | _ -> false

let trim_left source =
  let rec start offset =
    if offset < String.length source && space source.[offset] then start (offset + 1) else offset in
  let first = start 0 in
  String.sub source first (String.length source - first)

let trim_right source =
  let rec stop offset = if offset > 0 && space source.[offset - 1] then stop (offset - 1) else offset in
  String.sub source 0 (stop (String.length source))

let trim source = trim_right (trim_left source)
let drop count source = String.sub source count (String.length source - count)

let full_match pattern source =
  Str.string_match pattern source 0 && Str.match_end () = String.length source

let split_once delimiter source =
  match Str.search_forward (Str.regexp_string delimiter) source 0 with
  | offset -> Some (String.sub source 0 offset, drop (offset + String.length delimiter) source)
  | exception Not_found -> None

let go_header = Str.regexp "//[ \t]*Code generated .+ DO NOT EDIT\\.?[ \t]*"
let proto_header = Str.regexp "#[ \t]*Generated by the protocol buffer compiler\\.[ \t]+DO NOT EDIT!?[ \t]*"
let candace_marker = Str.regexp "code generated by candace\\(code\\)?gen"

let marked stripped content =
  full_match go_header stripped || full_match proto_header stripped ||
  let content = folded content in
  String.starts_with ~prefix:"this file is @generated by prost-build." content ||
  (Str.string_match candace_marker content 0 &&
   let finish = Str.match_end () in
   finish = String.length content || not (word_character content.[finish]))

let comment_prefixes = ["///"; "//!"; "//"; "#"; "--"]
let block_comments = ["/*", "*/"; "<!--", "-->"; "(*", "*)"; "/-", "-/"]

let begin_comment stripped =
  match List.find_opt (fun prefix -> String.starts_with ~prefix stripped) comment_prefixes with
  | Some prefix -> Some (trim_left (drop (String.length prefix) stripped), "", None)
  | None ->
      match List.find_opt (fun (prefix, _) -> String.starts_with ~prefix stripped) block_comments with
      | None -> None
      | Some (prefix, closer) ->
          let content = trim_left (drop (String.length prefix) stripped) in
          match split_once closer content with
          | None -> Some (content, "", Some closer)
          | Some (content, trailing) -> Some (trim_right content, trim trailing, None)

let continue_comment closer stripped =
  let content, trailing, ending = match split_once closer stripped with
    | Some (content, trailing) -> trim content, trim trailing, None
    | None -> stripped, "", Some closer in
  let content = if String.starts_with ~prefix:"*" content then trim_left (drop 1 content) else content in
  Some (content, trailing, ending)

let is_generated source =
  let rec inspect index ending = function
    | [] -> false
    | line :: rest ->
        let stripped = trim (normalized line) in
        if stripped = "" || (index = 0 && String.starts_with ~prefix:"#!" stripped) then
          inspect (index + 1) ending rest
        else
          let comment = match ending with
            | None -> begin_comment stripped
            | Some closer -> continue_comment closer stripped in
          match comment with
          | None -> false
          | Some (content, trailing, ending) ->
              if marked stripped content then true
              else if ending = None && trailing <> "" then false
              else inspect (index + 1) ending rest in
  inspect 0 None (physical_lines source)

let markdown_header = Str.regexp
  "<!--[ \t]*\\(code[ \t]+\\)?generated by [^<>]*[^<>a-z0-9_\128]do not edit[.!]?[ \t]*-->"
let diagram_marker = Str.regexp "<!--[ \t]*\\(/?\\)csf:diagram \\([a-z][a-z0-9_]*\\)[ \t]*-->"
let diagram_start = Str.regexp "\\(<!--[ \t]*\\)?/?csf:diagram"

let malformed_marker stripped =
  Str.string_match diagram_start stripped 0 &&
  let finish = Str.match_end () in
  finish = String.length stripped || not (word_character stripped.[finish])

let fence_run line =
  let length = String.length line in
  let rec spaces offset = if offset < length && line.[offset] = ' ' then spaces (offset + 1) else offset in
  let start = spaces 0 in
  if start > 3 || start = length || (line.[start] <> '`' && line.[start] <> '~') then None
  else
    let character = line.[start] in
    let rec finish offset = if offset < length && line.[offset] = character then finish (offset + 1) else offset in
    let stop = finish start in
    if stop - start < 3 then None else Some (character, stop - start, drop stop line)

let opening_fence line = match fence_run line with
  | Some ('`', _, info) when String.contains info '`' -> None
  | Some (character, width, _) -> Some (character, width)
  | None -> None

let closing_fence (character, width) line = match fence_run line with
  | Some (ending, count, trailing) -> ending = character && count >= width && trim trailing = ""
  | None -> false

let generated_diagram_lines ~name lines =
  let fail kind number = raise (Error (Printf.sprintf "%s marker: %s:%d" kind name number)) in
  let rec inspect number opened fence generated = function
    | [] -> (match opened with
        | None -> generated
        | Some diagram -> raise (Error (Printf.sprintf "unclosed diagram marker %s: %s" diagram name)))
    | line :: rest ->
        let line = normalized line in
        let advance opened fence generated = inspect (number + 1) opened fence generated rest in
        match fence with
        | Some delimiter -> advance opened (if closing_fence delimiter line then None else fence) generated
        | None ->
            let fence = if opened = None then opening_fence line else None in
            if fence <> None then advance opened fence generated
            else
              let stripped = trim line in
              if not (full_match diagram_marker stripped) then begin
                if malformed_marker stripped then fail "malformed diagram" number;
                advance opened None (if opened = None then generated else generated + 1)
              end else
                let closing = Str.matched_group 1 stripped = "/" in
                let diagram = Str.matched_group 2 stripped in
                if closing then begin
                  if opened <> Some diagram then fail "unmatched diagram end" number;
                  advance None None generated
                end else begin
                  if opened <> None then fail "nested diagram" number;
                  advance (Some diagram) None generated
                end in
  inspect 1 None None 0 lines

let documentation_generated_lines ~name source =
  let lines = physical_lines source in
  let header = List.find_map (fun line ->
    let line = trim (normalized line) in
    if line = "" then None else Some line) lines in
  let full_generated = match header with
    | Some header -> full_match markdown_header (folded header)
    | None -> false in
  let generated = generated_diagram_lines ~name lines in
  if full_generated then List.length lines else generated

#!/usr/bin/env python3
"""Project the protoc descriptor and OpenAPI document into typed Go adapters.

No independently maintained DTOs or route registry. This deliberately supports
only the GET-empty-input and POST-whole-message routes this contract uses.
"""
import copy
import json
from pathlib import Path
import sys
from google.protobuf import descriptor_pb2


def validate_operation_messages(service):
    """Require every annotated RPC to use operation-specific request/response messages."""
    failures = []
    for method in service.method:
        request = method.input_type.rsplit(".", 1)[1]
        response = method.output_type.rsplit(".", 1)[1]
        if request != method.name + "Request" or response != method.name + "Response":
            failures.append(f"{method.name}: {request} -> {response}")
    if failures:
        raise ValueError("RPCs require operation-specific *Request/*Response messages: " + "; ".join(failures))


def validate_get_request(path, request, message):
    if path and message.field:
        raise ValueError(f"GET route {path} requires an empty request message")


def schema_for_mcp(schema, components):
    result = copy.deepcopy(schema)
    # A tool receives only definitions reachable from its own request. Shipping
    # every response and unrelated tool schema multiplies agent context usage.
    required = {}
    def collect(value):
        if isinstance(value, dict):
            reference = value.get("$ref", "")
            prefix = "#/components/schemas/"
            if reference.startswith(prefix):
                name = reference[len(prefix):]
                if name not in required:
                    required[name] = copy.deepcopy(components[name])
                    collect(required[name])
            for item in value.values():
                collect(item)
        elif isinstance(value, list):
            for item in value:
                collect(item)
    collect(result)
    if required:
        result["$defs"] = required
    def visit(value):
        if isinstance(value, dict):
            for key, item in list(value.items()):
                if key == "$ref":
                    value[key] = item.replace("#/components/schemas/", "#/$defs/")
                else:
                    visit(item)
        elif isinstance(value, list):
            for item in value:
                visit(item)
    visit(result)
    return json.dumps(result, separators=(",", ":"), sort_keys=True)


def generate(root, output):
    descriptor = descriptor_pb2.FileDescriptorSet()
    descriptor.ParseFromString((root / "brainspine.descriptor.pb").read_bytes())
    source = next(file for file in descriptor.file if file.name == "adapter.proto")
    validate_operation_messages(source.service[0])
    comments = {}
    for index, method_descriptor in enumerate(source.service[0].method):
        for location in source.source_code_info.location:
            if list(location.path) == [6, 0, 2, index] and location.leading_comments:
                comments[method_descriptor.name] = " ".join(location.leading_comments.split())
    api = json.loads((root / "openapi/adapter.openapi.json").read_text())
    methods = {"Research_" + method.name: method for method in source.service[0].method}
    entries = []
    messages = {message.name: message for file in descriptor.file for message in file.message_type}
    for path, routes in sorted(api["paths"].items()):
        for verb, route in sorted(routes.items()):
            method = methods.pop(route["operationId"])
            request = method.input_type.rsplit(".", 1)[1]
            response = method.output_type.rsplit(".", 1)[1]
            if verb == "get" and request == "GetSnapshotRequest":
                validate_get_request(path, request, messages[request])
                input_schema = {"type": "object", "properties": {}, "additionalProperties": False}
            elif verb == "post":
                input_schema = route["requestBody"]["content"]["application/json"]["schema"]
            else:
                raise ValueError(f"unsupported contract route {verb} {path}")
            entries.append((method.name, request, response, verb.upper(), path,
                            route.get("summary", comments.get(method.name, "")),
                            schema_for_mcp(input_schema, api["components"]["schemas"])))
    if methods:
        raise ValueError(f"missing routes: {methods}")
    code = ['// Code generated by Candacegen (candace/csf/tools/codegen/generate_api.py). DO NOT EDIT.',
            'package csf', 'import ("context"; "encoding/json"; "fmt"; "strings";',
            '"google.golang.org/protobuf/encoding/protojson";',
            'pb "github.com/candacelabs/csf/proto/candace/brainspine/v1")',
            'func (service *Service) registerOperations() {']
    for name, request, response, verb, path, comment, schema in entries:
        literal = json.dumps(schema)
        code.append(f'registerOperation(service, "{name}", "{verb}", "{path}", {json.dumps(comment)}, json.RawMessage({literal}), func() *pb.{request} {{return &pb.{request}{{}}}}, service.{name})')
    code.append('}')
    for name, request, response, verb, path, comment, schema in entries:
        code += [f'func (client *Client) {name}(ctx context.Context, request *pb.{request}) (*pb.{response}, error) {{',
                 f'response := &pb.{response}{{}}',
                 f'if err := client.call(ctx, "{verb}", "{path}", request, response); err != nil {{ return nil, err }}',
                 'return response, nil', '}']
    # CLI, HTTP and MCP operation sets derive from the same annotated service.
    # The executable supplies transport/lifetime; no service owns a process.
    code += ['type HumanOperation struct { Name, Description string }',
             'func HumanOperations() []HumanOperation { return []HumanOperation{' + ','.join('{Name: '+json.dumps(entry[0])+', Description: '+json.dumps(entry[5])+'}' for entry in entries) + '} }',
             'func CLIOperations() []string { return []string{' + ','.join(json.dumps(entry[0]) for entry in entries) + '} }',
             'func (client *Client) CallOperation(ctx context.Context, operation string, input []byte) ([]byte, error) {',
             'switch strings.ToLower(operation) {']
    for name, request, response, *_ in entries:
        code += [f'case "{name.lower()}":',
                 f'request := &pb.{request}{{}}',
                 'if err := protojson.Unmarshal(input, request); err != nil { return nil, err }',
                 f'response, err := client.{name}(ctx, request)',
                 'if err != nil { return nil, err }',
                 'return (protojson.MarshalOptions{UseProtoNames: true}).Marshal(response)']
    code += ['default: return nil, fmt.Errorf("unknown operation %q; choose %v", operation, CLIOperations())', '}', '}']
    output.write_text('\n'.join(code) + '\n')


if __name__ == '__main__':
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
